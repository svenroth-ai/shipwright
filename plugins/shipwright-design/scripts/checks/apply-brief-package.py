#!/usr/bin/env python3
"""Design takes the Brief package (campaign brief-driven-run, B3a; BRIEF D8/D10).

When ``shipwright_run_config.json`` records ``brief_dir``, the supplied mockups are NOT
re-asked for in upload mode: ``screen-map.json`` answers the ``design.upload-screen-mapping``
question (which screen does each upload represent, and which requirements does it serve).

    uv run apply-brief-package.py --project-root <path>

* The package is re-verified (layout + hash held in run_config, approval) through
  ``brief_dir_intake.verify_run_config`` first; nothing is written for a refused package.
* Each mockup is copied BYTE-IDENTICAL to ``.shipwright/designs/uploads/<mockup>`` (the
  uploads-preserved gate keeps it that way) and, with the Linked-FR comment injected, to
  ``.shipwright/designs/screens/NN-<screen id>.html``. NN follows ``screen-map.json`` order.
* ``requirements`` in a screen-map entry are capability slugs (the lower-kebab form of the FR
  ``Name`` the brief headings give). The FR ids are the ones Project MINTED in
  ``.shipwright/planning/<split>/spec.md``; nobody picks an id here. A slug with no FR row
  stops the run: Project must finish first.
* Applying is recorded (``brief-package-applied.json`` holds the verified hash). A re-entry with the
  same hash returns ``already_applied`` and writes nothing, so review-loop edits survive; a different
  hash after an apply is refused. ``exists_differs`` therefore only guards the FIRST apply.
* ``visual-guidelines.md`` is taken from the package's ``design_system`` file and
  ``design-manifest.md`` is regenerated by the screen registry.

All checks run before the first write. Exit 0 ok, 1 package content issues, 3 package refused.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
# parents[0]=checks, [1]=scripts, [2]=shipwright-design, [3]=plugins, [4]=repo root.
_SHARED_SCRIPTS = Path(__file__).resolve().parents[4] / "shared" / "scripts"
if str(_SHARED_SCRIPTS) not in sys.path:
    sys.path.append(str(_SHARED_SCRIPTS))

from tools.grill_trace_fr_coverage import extract_fr_names, slugify  # noqa: E402

DESIGNS = ".shipwright/designs"
MARKER = "brief-package-applied.json"  # written last; its hash makes a re-entry a no-op


def _load(path: Path, name: str):
    """A module by file path under a private name (ADR-045: never bind ``lib``)."""
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def fr_ids_by_slug(project_root: Path) -> dict[str, list[str]]:
    """``{slug of the FR Name: [FR ids]}`` (more than one id = ambiguous) from the live FR rows of every split's spec.md."""
    out: dict[str, list[str]] = {}
    planning = project_root / ".shipwright" / "planning"
    for spec in sorted(planning.glob("*/spec.md")) if planning.is_dir() else []:
        if spec.parent.name == "iterate":
            continue
        for fr_id, name in extract_fr_names(spec.read_text(encoding="utf-8", errors="ignore")).items():
            out.setdefault(slugify(name), []).append(fr_id)
    return out


def _plan(bdir: Path, screen_map: dict, by_slug: dict[str, list[str]]) -> tuple[list[dict], list[dict]]:
    """``(planned screens, issues)``: every entry resolved to files and FR ids, or an issue."""
    plan: list[dict] = []
    issues: list[dict] = []
    seen: set[str] = set()
    seen_mockups: set[str] = set()
    for idx, entry in enumerate(screen_map.get("screens") or [], start=1):
        reqs = entry.get("requirements") if isinstance(entry, dict) else None
        if not isinstance(reqs, list) or not all(isinstance(r, str) for r in reqs):
            issues.append({"code": "bad_screen_map_entry", "screen": f"#{idx}",
                           "message": "a screen-map entry must be an object whose requirements is a list of capability slugs"})
            continue
        sid = slugify(str(entry.get("id") or ""))
        mock = str(entry.get("mockup") or "")
        src = bdir / "mockups" / mock
        wanted = [slugify(r) for r in reqs]
        frs = [by_slug[s][0] for s in wanted if len(by_slug.get(s, ())) == 1]
        problems = (
            ([f"screen id {entry.get('id')!r} is empty or repeated"] if not sid or sid in seen else [])
            + ([f"mockup {mock!r} is not an .html file (a screen is HTML)"] if not mock.lower().endswith(".html") else [])
            + ([f"mockup {mock!r} must be a plain file name inside mockups/"] if mock != Path(mock).name or mock in ("", ".", "..") else [])
            + ([f"mockup {mock!r} is missing"] if not src.is_file() else [])
            + [f"requirement {s!r} has no FR row in any spec.md (Project mints the ids)" for s in wanted if s not in by_slug]
            + [f"requirement {s!r} matches several FR rows {by_slug[s]}: ambiguous" for s in wanted if len(by_slug.get(s, ())) > 1]
            + ([] if wanted else ["no requirements: a screen must link at least one"])
        )
        seen.add(sid)
        if mock.casefold() in seen_mockups:
            problems.append(f"mockup {mock!r} is used by two screens")
        seen_mockups.add(mock.casefold())
        issues += [{"code": "bad_screen_map_entry", "screen": sid or f"#{idx}", "message": m} for m in problems]
        if not problems:
            plan.append({"id": sid, "mockup": mock, "src": src, "frs": list(dict.fromkeys(frs)),
                         "screen_file": f"{idx:02d}-{sid}.html"})
    return plan, issues


def apply(project_root: Path) -> dict:
    root = Path(project_root).resolve()
    bdi = _load(_SHARED_SCRIPTS / "lib" / "brief_dir_intake.py", "_shipwright_design_brief_dir_intake")
    info = bdi.verify_run_config(root)
    if not info.get("package"):
        raise bdi.BriefRefused("no_package", "run_config records no brief_dir: this run has no Brief package")
    bdir, _ = bdi.recorded_dir(bdi.load_config(root)["brief_dir"], root)
    designs = root / DESIGNS
    marker = designs / MARKER
    try:
        recorded = json.loads(marker.read_text(encoding="utf-8")) if marker.is_file() else {}
    except ValueError:
        recorded = None
    if not isinstance(recorded, dict):
        return {"ok": False, "issues": [{"code": "bad_marker", "screen": MARKER, "message": f"{MARKER} must hold a JSON object"}]}
    applied = recorded.get("package_sha256")
    if applied == info["package_sha256"]:  # re-entry: later edits (review loop) stay untouched
        return {"ok": True, "already_applied": True, "package_sha256": applied}
    if applied is not None:
        return {"ok": False, "issues": [{"code": "package_changed_since_apply", "screen": "-",
                "message": "the designs were applied from a different package hash: re-approve and restart Design, never re-apply over edited screens"}]}
    screen_map = json.loads((bdir / "screen-map.json").read_text(encoding="utf-8-sig"))
    plan, issues = _plan(bdir, screen_map, fr_ids_by_slug(root))
    registry = _load(_HERE.parent / "lib" / "screen_registry.py", "_shipwright_design_own_lib_screen_registry")
    brief = json.loads((bdir / "brief.json").read_text(encoding="utf-8-sig"))
    guidelines = bdir / str(brief.get("design_system") or "")
    if not guidelines.is_file():
        issues.append({"code": "missing_design_system", "screen": "-", "message": "brief.json design_system names no file in the package"})
    targets: list[tuple[Path, bytes]] = []
    for item in plan:
        src = item["src"].read_bytes()
        item["data"], item["page"] = src, registry.inject_requirements(src, item["frs"])
        targets += [(designs / "uploads" / item["mockup"], src), (designs / "screens" / item["screen_file"], item["page"])]
    if guidelines.is_file():
        targets.append((designs / "visual-guidelines.md", guidelines.read_bytes()))
    for path, data in targets:  # all checks first: a refusal writes nothing (first apply only)
        if path.is_file() and path.read_bytes() != data:
            issues.append({"code": "exists_differs", "screen": path.name, "message": f"{path.name} exists and differs from the package: never overwritten"})
    if issues:
        return {"ok": False, "issues": issues}
    atomic = bdi._lib("atomic_write").durable_atomic_write  # temp file + os.replace: a crash leaves no truncated file
    for path, data in targets:
        if not path.is_file():
            path.parent.mkdir(parents=True, exist_ok=True)
            atomic(path, data)
    registry.write_manifest(designs, profile_name=str(brief.get("profile") or ""))
    atomic(marker, json.dumps({"package_sha256": info["package_sha256"]}))
    return {"ok": True, "package_sha256": info["package_sha256"],
            "screens": [{"file": f"screens/{i['screen_file']}", "upload": f"uploads/{i['mockup']}", "frs": i["frs"]} for i in plan]}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--project-root", default=".")
    args = parser.parse_args(argv)
    try:
        out = apply(Path(args.project_root))
    except (OSError, ValueError) as exc:  # unreadable or malformed package files
        out = {"ok": False, "issues": [{"code": "unreadable_package", "screen": "-", "message": f"{type(exc).__name__}: {exc}"}]}
    except Exception as exc:  # BriefRefused is defined in the file-path-loaded module
        if type(exc).__name__ != "BriefRefused":
            raise
        print(json.dumps(exc.as_dict(), indent=2))
        return 3
    print(json.dumps(out, indent=2))
    return 0 if out["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
